#!/usr/bin/env python3
"""Build a portable copy of a repo-pii-scrub checkout for the Docker image.

    python tools/make_scrub_src.py ../skills/repo-pii-scrub          # -> build/scrub-src
    SCRUB_SRC=build/scrub-src docker compose build

The DataLabs workspace copy of repo-pii-scrub resolves its outputs through the
workspace's `datalabs_paths`, which does not exist in a container. This copies
only what the pipeline needs (an allow-list: no per-customer batch scripts, and
secrets such as the skill's `.salt`, or any `.venv`, can never be swept in) and swaps `workspace_paths.py` for a
layout-independent shim that exposes the same `out()` contract.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

INCLUDE = ("rules", "requirements.txt")
# Only the modules the pipeline imports or invokes. The workspace's scripts/ directory
# also holds per-customer batch drivers and repo catalogs; those must not ship in an image.
SCRIPTS = ("orchestrator.py", "steps.py", "state.py", "batch_env.py", "verify_deliverable.py",
           "remediate_deliverable.py", "scrub_metadata.py", "ner_service_manager.py")
SKIP_DIRS = {"__pycache__", ".venv", ".tools", "outputs", ".git"}
SKIP_SUFFIXES = (".pyc", ".bak", ".orig")

SHIM = '''"""Layout-independent stand-in for the DataLabs workspace_paths shim.

Generated by sample-scrub's tools/make_scrub_src.py. Exposes the one name the
orchestrator uses: out(), the root for run directories.
Override the location with PII_SCRUB_OUTPUTS_DIR.
"""

from __future__ import annotations

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def out(*parts: str) -> Path:
    base = Path(os.environ.get("PII_SCRUB_OUTPUTS_DIR") or ROOT / "outputs")
    return base.joinpath(*parts)


def out_dir(*parts: str) -> Path:
    p = out(*parts)
    p.mkdir(parents=True, exist_ok=True)
    return p
'''


def ignore(_dir, names):
    return [n for n in names if n in SKIP_DIRS or n.endswith(SKIP_SUFFIXES) or ".bak" in n or ".pre-" in n]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", help="a repo-pii-scrub checkout (e.g. DataLabs/skills/repo-pii-scrub)")
    ap.add_argument("--out", default="build/scrub-src")
    a = ap.parse_args(argv)
    src, dest = Path(a.src).resolve(), Path(a.out).resolve()
    if not (src / "scripts" / "orchestrator.py").is_file():
        print(f"error: {src} does not look like a repo-pii-scrub checkout", file=sys.stderr)
        return 1
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for name in INCLUDE:
        s = src / name
        if s.is_dir():
            shutil.copytree(s, dest / name, ignore=ignore)
        elif s.is_file():
            shutil.copy2(s, dest / name)
        else:
            print(f"warning: {name} missing in {src}", file=sys.stderr)
    # repo-sanitizer is not on PyPI; the Dockerfile installs it from git, so a plain
    # `repo-sanitizer>=x` requirement line would make `pip install -r` fail.
    req = dest / "requirements.txt"
    if req.is_file():
        keep = [l for l in req.read_text().splitlines() if not l.strip().lower().startswith("repo-sanitizer")]
        req.write_text("\n".join(keep) + "\n# repo-sanitizer: installed from git by the Dockerfile\n")
    (dest / "scripts").mkdir()
    for name in SCRIPTS:
        f = src / "scripts" / name
        if f.is_file():
            shutil.copy2(f, dest / "scripts" / name)
        else:
            print(f"warning: scripts/{name} missing in {src}", file=sys.stderr)
    (dest / "scripts" / "workspace_paths.py").write_text(SHIM)
    stray = [p for p in dest.rglob("*") if p.name in (".salt", ".env") or p.suffix in (".pem", ".key")]
    if stray:
        print(f"error: refusing to continue, secret-looking files copied: {stray}", file=sys.stderr)
        return 1
    n = sum(1 for p in dest.rglob("*") if p.is_file())
    print(f"wrote {dest} ({n} files); build with: SCRUB_SRC={Path(a.out)} docker compose build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
